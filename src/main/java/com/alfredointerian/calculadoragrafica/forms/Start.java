    /**
     * Crea una nuevo formulario para visualizar la vista del usuario
     * @param model Modelo del contenido del formulario
     */
    public Start(StartViewModel model) {        
        initComponents();
        try {
            for (Operator current : model.getOperators()) {
                Expression exp = new Expression(current.getFunction());    
                OperatorPanel op =  new OperatorPanel(current.getName(), exp.getInputVariables(), exp.getResultVariable(), current);
                FunctionPanel.addTab(current.getName(), op);
            }
        } catch (ExpressionException ex) {
            JOptionPane.showMessageDialog(this, "La expresión que se quiso utilizar no es válida debido a " + ex.getMessage(), "Error en la expresión matemática.", JOptionPane.ERROR_MESSAGE);
            this.dispose();
        }
    }

